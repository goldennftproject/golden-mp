'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const repo=path.resolve(__dirname,'..');
const {ctx}=require('./arrancar-el-juego.contexto').arrancar(repo);
const source=fs.readFileSync(path.join(repo,'supabase/functions/guardar/index.ts'),'utf8');
const rules=source.split('/* === REGLAS ===')[1].split('/* === FIN REGLAS === */')[0];
const server={Math,Number,Object,Array,JSON,Date,Set,String,isFinite};vm.createContext(server);vm.runInContext(rules.slice(rules.indexOf('const VERSION')),server);
const now=1800000000000,day=86400000,op=server.artefactoOperacion;
const before={golden:20,plata:3};
const bought=op(before,'comprar','cobre',now,'buy').data;
assert.equal(bought.golden,10);assert.equal(before.golden,20);
assert.ok(op(bought,'cobrar','cobre',now+day/6,'early').error,'no permite cobro antes de 24 horas');
const claimed=op(bought,'cobrar','cobre',now+day,'claim');
assert.equal(claimed.cobro,870);assert.equal(claimed.data.golden,10);assert.equal(claimed.data.plata,873);
ctx.G.artefactos=JSON.parse(JSON.stringify(bought.artefactos));
assert.equal(ctx.artefactoPendiente('cobre',now+day),claimed.cobro,'cliente y servidor coinciden');
assert.equal(ctx.artefactoPuedeCobrar('cobre',now+day/6),false);assert.equal(ctx.artefactoPuedeCobrar('cobre',now+day),true);
assert.equal(ctx.fmtGolden(0.018518),'0.018518');assert.equal(ctx.fmtGolden(10),'10');
const saved=JSON.parse(JSON.stringify(claimed.data));
assert.ok(!server.protegerEconomia(claimed.data,saved,now+day/6).some(s=>/Golden|objetos/.test(s)),'guardar un saldo fraccionario legítimo');
saved.golden+=1;assert.ok(server.protegerEconomia(claimed.data,saved,now+day/6).some(s=>/Emisión Golden/.test(s)),'no autoriza emisión desde el cliente');
const old={golden:10,plata:3,artefactos:{items:{cobre:{desde:now-day,cobrado:now-day,resto:0.09}},ops:[]}};
const cut=vm.runInContext('OBJETOS_PLATA_DESDE',server);
old.artefactos.items.cobre.desde=cut-day;old.artefactos.items.cobre.cobrado=cut-day;
assert.equal(server.artefactoCalcular(old.artefactos.items.cobre,'cobre',cut).cobro,0,'no transforma plata histórica en Golden');
const html=fs.readFileSync(path.join(repo,'public/index.html'),'utf8');
assert.ok(html.includes('data-panel="ov-reliquias"'));
assert.ok(!html.split('id="ov-cobertizo"')[1].split('id="ov-reliquias"')[0].includes('id="objetos-productores"'));
ctx.refreshArtefactos();
assert.equal(vm.runInContext("typeof OV_REFRESH['ov-reliquias']",ctx),'function');
assert.ok(fs.readFileSync(path.join(repo,'public/game/ui.js'),'utf8').includes('G.golden, fmtGolden'));
console.log('OK: Objetos de Granja independientes, Plata diaria, sin conversión histórica, cliente/servidor coinciden y guardado protege emisión.');
