"use strict";
const assert = require("node:assert/strict"), vm = require("node:vm"), path = require("node:path"), fs = require("node:fs");
const { ctx, problemas } = require("./arrancar-el-juego.contexto.js").arrancar(path.resolve(__dirname, ".."));
assert.equal(problemas.filter(p => p.grave).length, 0);
const run = s => vm.runInContext(s, ctx);
run("var relojMercadoTest = 1800000000000; nowMs = () => relojMercadoTest; G.level=1; G.mercadoVentas={};");
assert.equal(run('totalVenta("papa",3)'), 6, "venta inicial del tutorial intacta");
const lote = run('totalVenta("papa",100)');
const dividido = run(`(() => { let total=0; for(let i=0;i<100;i++){const d=cotizarVenta('papa',1);total+=d.total;registrarVenta('papa',1,d);} return total; })()`);
assert.equal(dividido, lote, "dividir ventas no aumenta el cobro");
assert.ok(run('precioVenta("papa") < precioVentaBase("papa")'));
assert.equal(run('totalVenta("zanahoria",3)'), run('Math.floor(precioVentaBase("zanahoria")*3+1e-9)'), "otro recurso mantiene su precio");
const deprimido = run('precioVenta("papa")');
run('relojMercadoTest+=8*3600000');
assert.ok(run('precioVenta("papa")') > deprimido, "el precio se recupera con el tiempo");
assert.ok(run('precioVenta("papa") > CROP_DEF.papa.seedCost'), "piso cubre semilla y margen");
const antes = run('JSON.stringify(G.mercadoVentas)');
for (const q of [-1, 0.5, NaN, Infinity, 1000000001]) assert.equal(run(`totalVenta('papa',${q})`), 0);
assert.equal(run('JSON.stringify(G.mercadoVentas)'), antes, "cotizar no cambia estado");
const min = run('ventaMinGolden("papa")');
assert.ok(run(`totalVenta('papa',${min})>=GOLDEN_EN_PLATA`));
assert.ok(run(`totalVenta('papa',${min-1})<GOLDEN_EN_PLATA`));
run(`var copiaMercadoTest=JSON.parse(JSON.stringify(snapshot())); G.mercadoVentas={}; hydrate(copiaMercadoTest);`);
assert.equal(run('JSON.stringify(G.mercadoVentas)'), antes, "presión y fracciones sobreviven al guardado");
run(`var dolarAntesTest=$;refreshMarket=()=>{};refreshHud=()=>{};refreshHotbar=()=>{};syncSlots=()=>{};isOpen=()=>false;saveFarm=()=>{};tutoActivo=()=>null;log=()=>{};toast=()=>{};tutoEvent=()=>{};
  $=()=>({value:'10'});G.res.papa=20;G.plata=0;marketCur='plata';var esperadoMercadoTest=totalVenta('papa',10);sellItem('papa');`);
assert.equal(run('G.plata'), run('esperadoMercadoTest'));
assert.equal(run('G.res.papa'), 10, "venta real consume el lote");
run(`G.mercadoVentas={};G.res.papa=10;marketCur='golden';var plataAntesTest=G.plata;var goldenAntesTest=G.golden;sellItem('papa');`);
assert.equal(run('G.res.papa'), 10, "venta rechazada no consume recursos");
assert.equal(run('Object.keys(G.mercadoVentas).length'), 0, "venta rechazada no deprime precios");
assert.equal(run('G.golden'), run('goldenAntesTest'));
assert.equal(run('G.plata'), run('plataAntesTest'));
run('$=dolarAntesTest;hydrate({plata:47});');
assert.equal(run('G.plata'), 47); assert.equal(run('Object.keys(G.mercadoVentas).length'), 0, "partida antigua inicia mercado sin perder plata");
const html = fs.readFileSync(path.resolve(__dirname, "../public/index.html"), "utf8");
assert.ok(!html.includes('href="economia.html"'));
assert.ok(!fs.existsSync(path.resolve(__dirname, "../public/economia.html")));
console.log("OK: mercado real, tutorial, lotes, diversificación, recuperación, piso, cotización pura, Golden, guardado, venta y retirada del laboratorio.");
