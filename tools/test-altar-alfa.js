const assert = require('node:assert/strict');
const path = require('path'), vm = require('vm');
const {ctx} = require('./arrancar-el-juego.contexto.js').arrancar(path.join(__dirname,'..'));
const run = code => vm.runInContext(code,ctx);
run(`G.level=20; G.tuto={done:true}; G.planos={altar:1,ofrendas:1}; G.built={altar:true,ofrendas:true}; G.obras={altar:{col:2,row:2}}; G.obraDep={altar:{tablon:3}}; G.res.madera=100;`);
const before=JSON.stringify(ctx.G);
for(const code of ['darPlano("altar")','obraColocar("altar",3,3)','obraDepositar("altar")','obraConstruir("altar")','ofrendar("madera",10)','upgradeWeapon("espada",true,true)','craftAltarItem("polvo")','craftRunaI("fuego")','fuseRuna("fuego",1)','socketRuna("espada",0,null,1)'])run(code);
assert.equal(JSON.stringify(ctx.G),before,'No borra ni gasta progreso conservado');
assert.equal(run('GF.objetoPresente({tipo:"altar",i:1})'),false);
assert.equal(run('GF.objetoPresente({tipo:"ofrendas",i:1})'),false);
assert.equal(run('cobertizoItems().some(d=>["altar","ofrendas"].includes(d.key))'),false);
assert.equal(run('Array.from({length:50},(_,i)=>farmUnlockTxt(i+1)).some(s=>/altar/i.test(s))'),false);
assert.equal(run('TUTO_STEPS.some(s=>/altar|ofrenda/i.test(JSON.stringify(s)))'),false);
run('openOv("ov-altar");openOv("ov-ofrendas")');
assert.equal(run('isOpen("ov-altar")||isOpen("ov-ofrendas")'),false);
assert.equal(run('caminoGuarida().hitos.some(h=>h.titulo==="Las piedras que zumban")'),false);
run('GF.ALTAR_ACTIVO=true; G.produccion=null');
assert.equal(run('GF.objetoPresente({tipo:"altar",i:1})'),true);
assert.equal(run('cobertizoItems().filter(d=>["altar","ofrendas"].includes(d.key)).length'),2);
assert.equal(run('caminoGuarida().hitos.some(h=>h.titulo==="Las piedras que zumban")'),true);
console.log('OK: altar pausado, sin accesos/referencias de progresiÃ³n, estado intacto y restauraciÃ³n por bandera.');
